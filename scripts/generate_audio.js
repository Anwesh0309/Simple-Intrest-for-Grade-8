/* =========================================================================
   OFFLINE AUDIO GENERATION — ElevenLabs "Alice" with seamless TTS Fallback
   Usage:  node scripts/generate_audio.js           (skips files that exist)
           node scripts/generate_audio.js --force   (re-generate everything)
   • Reads phrases from src/utils/lessonScript.js (same text the UI shows)
   • Primary: ElevenLabs API (Voice: Xb7hH8MSUJpSbSDYk0k2)
   • Fallback: Google TTS (generates authentic .mp3 files when ElevenLabs quota is reached)
   • Saves MP3s to public/assets/audio/ and writes src/utils/audioMap.js
   ========================================================================= */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { ALL_PHRASES } from '../src/utils/lessonScript.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public', 'assets', 'audio');
const MAP_FILE = path.join(ROOT, 'src', 'utils', 'audioMap.js');

const VOICE_ID = 'Xb7hH8MSUJpSbSDYk0k2';
const MODEL_ID = 'eleven_multilingual_v2';

const STYLE_SETTINGS = {
  celebration:   { stability: 0.12, similarity_boost: 0.45, style: 0.75, use_speaker_boost: true },
  encouragement: { stability: 0.16, similarity_boost: 0.50, style: 0.65, use_speaker_boost: true },
  question:      { stability: 0.20, similarity_boost: 0.55, style: 0.55, use_speaker_boost: true },
  emphasis:      { stability: 0.16, similarity_boost: 0.50, style: 0.60, use_speaker_boost: true },
  thinking:      { stability: 0.24, similarity_boost: 0.60, style: 0.35, use_speaker_boost: true },
  statement:     { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true },
  instruction:   { stability: 0.20, similarity_boost: 0.55, style: 0.50, use_speaker_boost: true }
};

function readEnvKey() {
  if (process.env.VITE_ELEVENLABS_API_KEY) return process.env.VITE_ELEVENLABS_API_KEY;
  for (const f of ['.env.local', '.env']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const m = fs.readFileSync(p, 'utf8').match(/^\s*VITE_ELEVENLABS_API_KEY\s*=\s*"?([^"\r\n]+)"?/m);
    if (m) return m[1].trim();
  }
  return '';
}

const slugify = text =>
  text.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 50);

const sleep = ms => new Promise(r => setTimeout(r, ms));

function saveMap(map) {
  const out =
    '/* =========================================================================\n' +
    '   AUTO-GENERATED by scripts/generate_audio.js — do not edit by hand.\n' +
    '   Key: exact spoken text  →  Value: pre-generated MP3 path.\n' +
    '   ========================================================================= */\n' +
    `export const audioMap = ${JSON.stringify(map, null, 2)};\n`;
  fs.writeFileSync(MAP_FILE, out);
}

async function fetchGoogleTTS(text) {
  const chunks = [];
  let remaining = text;
  while (remaining.length > 0) {
    if (remaining.length <= 180) {
      chunks.push(remaining);
      break;
    }
    let idx = remaining.slice(0, 180).lastIndexOf('. ');
    if (idx === -1) idx = remaining.slice(0, 180).lastIndexOf(', ');
    if (idx === -1) idx = remaining.slice(0, 180).lastIndexOf(' ');
    if (idx === -1) idx = 180;
    else idx += 1;
    chunks.push(remaining.slice(0, idx).trim());
    remaining = remaining.slice(idx).trim();
  }

  const buffers = [];
  for (const c of chunks) {
    const url = 'https://translate.google.com/translate_tts?ie=UTF-8&q=' + encodeURIComponent(c) + '&tl=en&client=tw-ob';
    const res = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0' } });
    if (!res.ok) throw new Error('Google TTS HTTP ' + res.status);
    buffers.push(Buffer.from(await res.arrayBuffer()));
    await sleep(80);
  }
  return Buffer.concat(buffers);
}

async function main() {
  const force = process.argv.includes('--force');
  const apiKey = readEnvKey();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const seen = new Set();
  const phrases = ALL_PHRASES.filter(p => {
    if (!p.text || seen.has(p.text)) return false;
    seen.add(p.text);
    return true;
  });

  console.log(`Starting audio generation for ${phrases.length} unique phrases...`);

  // Load existing audioMap if available
  let map = {};
  if (fs.existsSync(MAP_FILE)) {
    try {
      const content = fs.readFileSync(MAP_FILE, 'utf8');
      const m = content.match(/export const audioMap = (\{[\s\S]*?\});/);
      if (m) map = JSON.parse(m[1]);
    } catch (e) {}
  }

  let made = 0, skipped = 0, fallbackCount = 0, failed = 0;
  let elevenLabsQuotaExceeded = false;

  for (const [i, p] of phrases.entries()) {
    const hash = crypto.createHash('md5').update(p.text).digest('hex').slice(0, 6);
    const fileName = `audio_${slugify(p.text)}_${hash}.mp3`;
    const filePath = path.join(OUT_DIR, fileName);
    const publicPath = `/assets/audio/${fileName}`;

    if (!force && fs.existsSync(filePath) && fs.statSync(filePath).size > 0) {
      map[p.text] = publicPath;
      skipped++;
      continue;
    }

    const s = STYLE_SETTINGS[p.style] || STYLE_SETTINGS.statement;
    process.stdout.write(`[${i + 1}/${phrases.length}] (${p.style}) ${p.text.slice(0, 50)}… `);

    let audioBuffer = null;

    if (apiKey && !elevenLabsQuotaExceeded) {
      try {
        const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
          method: 'POST',
          headers: { 'xi-api-key': apiKey, 'Content-Type': 'application/json', Accept: 'audio/mpeg' },
          body: JSON.stringify({ text: p.text, model_id: MODEL_ID, voice_settings: s })
        });
        if (res.ok) {
          audioBuffer = Buffer.from(await res.arrayBuffer());
          made++;
          console.log('✔ (ElevenLabs)');
        } else {
          const errText = await res.text();
          if (res.status === 401 && errText.includes('quota_exceeded')) {
            console.log('\n[ElevenLabs 10k monthly quota reached. Seamlessly switching to MP3 generator for remaining files]');
            elevenLabsQuotaExceeded = true;
          } else {
            console.log(`(ElevenLabs error: ${res.status})`);
          }
        }
      } catch (e) {
        console.log(`(ElevenLabs network error)`);
      }
    }

    if (!audioBuffer) {
      try {
        audioBuffer = await fetchGoogleTTS(p.text);
        fallbackCount++;
        console.log('✔ (MP3 generated)');
      } catch (e) {
        failed++;
        console.log(`✖ ${e.message}`);
      }
    }

    if (audioBuffer) {
      fs.writeFileSync(filePath, audioBuffer);
      map[p.text] = publicPath;
    }

    if ((made + skipped + fallbackCount) % 10 === 0) {
      saveMap(map);
    }

    await sleep(200);
  }

  saveMap(map);

  console.log(`\n========================================`);
  console.log(`DONE! Total phrases: ${phrases.length}`);
  console.log(`• ElevenLabs Alice MP3s: ${made + skipped}`);
  console.log(`• Fallback MP3s: ${fallbackCount}`);
  console.log(`• Failed: ${failed}`);
  console.log(`• Map entries: ${Object.keys(map).length}/${phrases.length}`);
  console.log(`========================================\n`);
  if (failed) process.exitCode = 1;
}

main();
